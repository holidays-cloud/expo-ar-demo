const { chromium } = require('playwright');
const [SP, doc, vw = '390', vh = '844', base = 'http://localhost:8080/'] = process.argv.slice(2);
const tag = vw + 'x' + vh;
(async () => {
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', `--use-file-for-fake-video-capture=${SP}/${doc}-still.y4m`] });
  const ctx = await browser.newContext({ viewport: { width: +vw, height: +vh }, isMobile: true, hasTouch: true, permissions: ['camera'] });
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', (e) => errs.push(e.message));
  page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  await page.goto(base);
  if (doc === 'doc1') await page.screenshot({ path: `${SP}/n-intro.png` });
  await page.click('text=باز کردن دوربین');
  const t0 = Date.now();
  await page.waitForFunction(() => { const h = document.querySelector('.hint'); return !h || h.hidden || h.textContent.includes('عمودی'); }, null, { timeout: 60000 });
  const found = (Date.now() - t0) / 1000;
  await page.waitForTimeout(2200);
  await page.screenshot({ path: `${SP}/n-${doc}-${tag}-anim.png` });
  const hintNow = await page.locator('.hint').textContent().catch(() => '');
  await page.waitForSelector('text=دیدن نتیجه', { timeout: 60000 });
  await page.screenshot({ path: `${SP}/n-${doc}-${tag}-end.png` });
  await page.click('text=دیدن نتیجه');
  await page.waitForSelector('.paper');
  const prepared = await page.locator('.prepared').textContent();
  await page.screenshot({ path: `${SP}/n-${doc}-${tag}-result.png`, fullPage: false });
  await page.click('text=اسکن برگهٔ بعدی');
  await page.waitForTimeout(500);
  const overlayGone = (await page.locator('.overlay').count()) === 0;
  const filled = await page.locator('.pdot.filled').count();
  console.log(`${doc} ${tag}: hint during animation="${hintNow}"; found after ${found.toFixed(1)} s, result shown, note="${prepared}", back to camera=${overlayGone}, filled dots=${filled}, errors=${errs.length ? errs.join(' | ') : 'none'}`);
  await browser.close();
})().catch((e) => { console.log(doc, 'FAILED', e.message.split('\n')[0]); process.exit(1); });
